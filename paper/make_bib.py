# References without a DOI, each checked by hand against the source named in its comment.
MANUAL = [
    # No DOI; JSTOR stable record 4615733, supplied by the author for the DockPrepBench paper.
    """@article{holm1979,
  author  = {Holm, Sture},
  title   = {A Simple Sequentially Rejective Multiple Test Procedure},
  journal = {Scandinavian Journal of Statistics},
  year    = {1979},
  volume  = {6},
  number  = {2},
  pages   = {65--70},
  url     = {http://www.jstor.org/stable/4615733},
}""",
]


def fetch(doi):
    """Fetch a BibTeX entry for a DOI by content negotiation.

    Args:
        doi (str): The DOI.

    Returns:
        str: The BibTeX entry.
    """
    request = urllib.request.Request(
        f"https://doi.org/{doi}", headers={"Accept": "application/x-bibtex; charset=utf-8", "User-Agent": "make_bib/0.1"}
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8").strip()


def main():
    """Fetch every reference and write references.bib with our citation keys."""
    entries = []
    for key, doi in REFERENCES.items():
        entry = fetch(doi)
        entry = re.sub(r"^@(\w+)\{[^,]*,", lambda m: f"@{m.group(1)}{{{key},", entry, count=1)
        entries.append(entry)
        print(key, "ok", flush=True)
        time.sleep(1)
    entries += MANUAL
    header = "% Generated by make_bib.py from DOIs (Crossref / DataCite). Do not edit; edit REFERENCES there.\n\n"
    (Path(__file__).parent / "references.bib").write_text(header + "\n\n".join(entries) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
